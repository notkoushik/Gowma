import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const dir = path.join(__dirname, '..', 'src', 'assets', 'landing');
const files = fs.readdirSync(dir).filter(f => f.endsWith('.jpg') || f.endsWith('.png'));

let tsContent = '/** Autogenerated Base64 Image Assets to guarantee 100% reliable rendering without Git LFS dependency **/\n\n';

for (const file of files) {
  const ext = path.extname(file).replace('.', '');
  const mime = ext === 'png' ? 'image/png' : 'image/jpeg';
  const data = fs.readFileSync(path.join(dir, file));
  const b64 = data.toString('base64');
  
  // convert name like hero_sacred_cow.jpg to heroSacredCow
  const baseName = path.basename(file, path.extname(file));
  const varName = baseName.replace(/_([a-z0-9])/g, (_, g) => g.toUpperCase());
  
  tsContent += `export const ${varName} = "data:${mime};base64,${b64}";\n`;
}

fs.writeFileSync(path.join(dir, 'imagesData.ts'), tsContent);
console.log('Generated imagesData.ts successfully. File size:', (fs.statSync(path.join(dir, 'imagesData.ts')).size / 1024).toFixed(1), 'KB');
