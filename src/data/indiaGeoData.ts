/**
 * Returns all 36 Indian states and union territories in alphabetical order
 */
export function getAllIndianStates(): string[] {
  return INDIA_STATES_AND_DISTRICTS.map((s) => s.state)
}

/**
 * Returns all districts for a given Indian state/UT
 */
export function getDistrictsForIndianState(stateName: string): string[] {
  if (!stateName) return []
  const norm = stateName.trim().toLowerCase()
  const found = INDIA_STATES_AND_DISTRICTS.find(
    (s) => s.state.toLowerCase() === norm,
  )
  return found ? [...found.districts] : []
}

/**
 * Get default zone for a given Indian state
 */
export function getDefaultZoneForState(
  stateName: string,
): "North" | "South" | "East" | "West" | "Central" | "Rural" {
  if (!stateName) return "Central"
  const norm = stateName.trim().toLowerCase()
  const found = INDIA_STATES_AND_DISTRICTS.find(
    (s) => s.state.toLowerCase() === norm,
  )
  return found?.defaultZone || "Central"
}
